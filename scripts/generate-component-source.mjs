// Bundles component, example, and block source into app/component-source.generated.ts
// so docs pages can show the exact files the CLI installs.
import { readFile, writeFile } from "node:fs/promises"
import { resolve } from "node:path"

const root = resolve(import.meta.dirname, "..")
const read = (path) => readFile(resolve(root, path), "utf8")
const catalog = JSON.parse(await read("registry/catalog.json"))

async function collect(entries, key) {
  return Object.fromEntries(await Promise.all(entries.map(async (entry) => [entry.name, await read(entry[key])])))
}

const componentSource = await collect(catalog.components, "file")
const exampleSource = await collect(catalog.components, "example")
const blockSource = await collect(catalog.blocks, "file")
const designSource = await read("public/DESIGN.md")

const output = [
  "// Generated by scripts/generate-component-source.mjs. Do not edit.",
  `export const componentSource: Record<string, string> = ${JSON.stringify(componentSource, null, 2)}`,
  `export const exampleSource: Record<string, string> = ${JSON.stringify(exampleSource, null, 2)}`,
  `export const blockSource: Record<string, string> = ${JSON.stringify(blockSource, null, 2)}`,
  `export const designSource = ${JSON.stringify(designSource)}`,
  "",
].join("\n\n")

await writeFile(resolve(root, "app/component-source.generated.ts"), output)
